"""Shared constants exported from the TypeScript sources (single source of truth).

The JSON under app/catalog/data is GENERATED by `node backend/tools/export_catalog.mjs` (tests/unit/test_catalog_sync.py
fails when it is stale). Usage:

    from app.catalog import cat
    PLANS = cat('mock/routes/billing')['PLANS']          # module path as in src/, without extension
    DEFAULT_SETTINGS = cat('mock/seed')['DEFAULT_SETTINGS']

Values are deep-frozen (read-only) — copy before changing: `{**DEFAULT_THEME}`, `list(x)`, `thaw(x)`. A TS `Set`
constant is a frozenset. Constants holding functions are not exported (see "$skipped" in the JSON) and are ported by
hand next to the code that uses them.
"""

from __future__ import annotations

import functools
import json
import os
from typing import Any

from app.frozen import freeze

DATA = os.path.join(os.path.dirname(__file__), 'data')


@functools.cache
def cat(module: str) -> dict[str, Any]:
    path = os.path.join(DATA, module + '.json')
    with open(path, encoding='utf-8') as f:
        raw = json.load(f)
    types = raw.pop('$types', {})
    raw.pop('$skipped', None)
    out = {}
    for k, v in raw.items():
        out[k] = frozenset(v) if types.get(k) == 'set' else freeze(v)
    return out


def const(module: str, name: str) -> Any:
    """one constant: const('mock/routes/billing', 'PLANS')"""
    return cat(module)[name]


DB_KEYS: tuple[str, ...] = tuple(cat('tables')['DB_KEYS'])
