class Undefined:
    """The JS `undefined` value. Falsy. JSON: dropped as an object value, `null` as an array item.

    Use it where the TypeScript distinguishes a missing value from `null` (optional fields, `?? fallback`)."""

    __slots__ = ()
    _inst: Undefined | None = None

    def __new__(cls) -> Undefined:
        if cls._inst is None:
            cls._inst = super().__new__(cls)
        return cls._inst

    def __bool__(self) -> bool:
        return False

    def __repr__(self) -> str:
        return 'UNDEF'

    def __reduce__(self) -> str:
        return 'UNDEF'


UNDEF = Undefined()


def nullish(v: Any) -> bool:
    """`v == null` in JS (null or undefined)."""
    return v is None or v is UNDEF


def coalesce(*vals: Any) -> Any:
    """`a ?? b ?? c`: the first value that is neither null nor undefined (else the last value)."""
    for v in vals[:-1]:
        if v is not None and v is not UNDEF:
            return v
    return vals[-1] if vals else UNDEF


def js_truthy(v: Any) -> bool:
    """JS truthiness: '' 0 NaN null undefined false are falsy; [] and {} are TRUTHY (unlike Python)."""
    if v is None or v is UNDEF or v is False:
        return False
    if v is True:
        return True
    if isinstance(v, (int, float)):
        return v == v and v != 0
    if isinstance(v, str):
        return v != ''
    return True


def js_or(*vals: Any) -> Any:
    """`a || b || c`: the first truthy value, else the last."""
    for v in vals[:-1]:
        if js_truthy(v):
            return v
    return vals[-1] if vals else UNDEF


def js_and(*vals: Any) -> Any:
    """`a && b && c`: the first falsy value, else the last."""
    for v in vals[:-1]:
        if not js_truthy(v):
            return v
    return vals[-1] if vals else UNDEF


def js_typeof(v: Any) -> str:
    if v is UNDEF:
        return 'undefined'
    if v is None:
        return 'object'
    if isinstance(v, bool):
        return 'boolean'
    if isinstance(v, (int, float)):
        return 'number'
    if isinstance(v, str):
        return 'string'
    if callable(v):
        return 'function'
    return 'object'


