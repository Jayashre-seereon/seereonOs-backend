def cmp_str(a: str, b: str) -> int:
    """`a < b ? -1 : a > b ? 1 : 0` on strings (UTF-16 code-unit order, = code point order for BMP text)."""
    if a == b:
        return 0
    return -1 if _utf16_key(a) < _utf16_key(b) else 1


def _utf16_key(s: str) -> Any:
    # code point order equals UTF-16 order unless astral characters meet U+E000..U+FFFF; handle that rare case
    if all(ord(c) <= 0xFFFF for c in s):
        return s
    return s.encode('utf-16-be')


class _Collation:
    def __init__(self) -> None:
        path = os.path.join(os.path.dirname(__file__), 'js_collation.json')
        with open(path, encoding='utf-8') as f:
            d = json.load(f)
        self.weights: dict[str, tuple[int, int, float]] = {k: tuple(v) for k, v in d['weights'].items()}  # type: ignore[misc]
        self.marks: dict[str, tuple[int, int, float]] = {k: tuple(v) for k, v in d['marks'].items()}  # type: ignore[misc]
        self.max_primary = d['max_primary']
        self.expansions: dict[str, list[tuple[int, int, float]]] = {}
        for ch, e in d['expansions'].items():
            els = [el for c in e['to'] for el in self._elements_of_char(c)]
            if e['cmp'] > 0:
                bump = 10 if e.get('cmp_upper', 0) > 0 else 0.5  # ß sorts after SS: above every case variant
                els = [(p, s, t + bump) for (p, s, t) in els]
            elif e['cmp'] < 0:
                els = [(p, s, t - 0.5) for (p, s, t) in els]
            self.expansions[ch] = els
        self.zero_p = self.weights['0'][0]
        self.nine_p = self.weights['9'][0]
        self._cache: dict[str, tuple[Any, Any, Any]] = {}
        self._ncache: dict[str, tuple[Any, Any, Any]] = {}

    def _elements_of_char(self, c: str) -> list[tuple[int, int, float]]:
        w = self.weights.get(c)
        if w is not None:
            return [w]
        m = self.marks.get(c)
        if m is not None:
            return [m]
        e = getattr(self, 'expansions', {}).get(c)
        if e is not None:
            return e
        # outside the derived blocks: implicit weights after every explicit primary, in code point order
        return [(self.max_primary + 1 + ord(c), 1, 1)]

    def key(self, s: str, numeric: bool = False) -> tuple[Any, Any, Any]:
        cache = self._ncache if numeric else self._cache
        k = cache.get(s)
        if k is not None:
            return k
        t = unicodedata.normalize('NFD', s) if not s.isascii() else s
        p1: list[Any] = []
        p2: list[Any] = []
        p3: list[Any] = []
        i = 0
        n = len(t)
        while i < n:
            c = t[i]
            if numeric and '0' <= c <= '9':
                j = i
                while j < n and '0' <= t[j] <= '9':
                    j += 1
                p1.append((self.zero_p, int(t[i:j])))
                p2.append(1)
                p3.append(1)
                i = j
                continue
            for p, s2, t3 in self._elements_of_char(c):
                if p:
                    p1.append((p, 0) if numeric else p)
                if s2:
                    p2.append(s2)
                if t3:
                    p3.append(t3)
            i += 1
        k = (tuple(p1), tuple(p2), tuple(p3))
        if len(cache) > 200_000:
            cache.clear()
        cache[s] = k
        return k


_COLL: _Collation | None = None


def _coll() -> _Collation:
    global _COLL
    if _COLL is None:
        _COLL = _Collation()
    return _COLL


def locale_compare(a: str, b: str) -> int:
    """a.localeCompare(b) (default locale of the Node reference = ICU root collation, tertiary strength)."""
    if a == b:
        return 0
    ka, kb = _coll().key(a), _coll().key(b)
    return -1 if ka < kb else 1 if ka > kb else 0


def locale_key(s: str) -> tuple[Any, Any, Any]:
    """sort key equivalent to locale_compare (use with sorted(key=...) — faster than cmp_to_key)."""
    return _coll().key(s)


def compare_numeric(a: str, b: str) -> int:
    """new Intl.Collator(undefined, { numeric: true }).compare(a, b) (src/domain/collate.ts compareNumeric)."""
    if a == b:
        return 0
    ka, kb = _coll().key(a, True), _coll().key(b, True)
    return -1 if ka < kb else 1 if ka > kb else 0


def numeric_key(s: str) -> tuple[Any, Any, Any]:
    return _coll().key(s, True)


def _cmp_result(r: Any) -> int:
    """a JS comparator result as -1/0/1 (NaN / undefined / non-numbers count as 0; booleans as 1/0)."""
    if r is True:
        return 1
    if r is False or r is None or r is UNDEF:
        return 0
    if isinstance(r, (int, float)):
        if r != r:
            return 0
        return -1 if r < 0 else 1 if r > 0 else 0
    n = js_number(r)
    return 0 if n != n or n == 0 else (-1 if n < 0 else 1)


def js_sort(items: Iterable[Any], cmp: Callable[[Any, Any], Any] | None = None) -> list[Any]:
    """[...items].sort(cmp) — returns a NEW list (never sort cached rows in place). Stable like V8 (TimSort).

    Without a comparator JS sorts by String(x) in UTF-16 order, undefined last."""
    lst = list(items)
    if cmp is None:
        undef = [x for x in lst if x is UNDEF]
        rest = [x for x in lst if x is not UNDEF]
        rest.sort(key=lambda x: _utf16_key(js_str(x)))
        return rest + undef
    return sorted(lst, key=functools.cmp_to_key(lambda a, b: _cmp_result(cmp(a, b))))


def by(*keys: Callable[[Any], Any]) -> Callable[[Any, Any], int]:
    """comparator chaining helper: by(lambda r: locale_key(r['name'])) …; each key result compared with < / >."""

    def c(a: Any, b: Any) -> int:
        for k in keys:
            x, y = k(a), k(b)
            if x < y:
                return -1
            if x > y:
                return 1
        return 0

    return c


