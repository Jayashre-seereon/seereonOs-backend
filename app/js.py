def prepare_json(v: Any) -> Any:
    """Make a value serialise exactly like JSON.stringify: drop UNDEF object values, UNDEF array items -> null,
    integral floats -> ints ('8' not '8.0'), NaN/±Infinity -> null, tuples/sets -> lists. Returns a new structure only
    where something changed (shared sub-structures are reused)."""
    t = type(v)
    if t is str or t is int or t is bool or v is None:
        return v
    if t is float:
        return _json_float(v)
    if isinstance(v, dict):
        out = None
        for k, x in v.items():
            tx = type(x)
            if tx is str or tx is int or tx is bool or x is None:
                if out is not None:
                    out[k] = x
                continue
            if x is UNDEF:
                if out is None:
                    out = _copy_until(v, k)
                continue
            y = prepare_json(x)
            if y is not x and out is None:
                out = _copy_until(v, k)
            if out is not None:
                out[k] = y
        return v if out is None else out
    if isinstance(v, (list, tuple)):
        outl = None
        for i, x in enumerate(v):
            tx = type(x)
            if tx is str or tx is int or tx is bool or x is None:
                if outl is not None:
                    outl.append(x)
                continue
            y = None if x is UNDEF else prepare_json(x)
            if (y is not x or t is not list) and outl is None:
                outl = list(v[:i])
            if outl is not None:
                outl.append(y)
        if outl is None and t is not list:
            return list(v)
        return v if outl is None else outl
    if v is UNDEF:
        return None
    if isinstance(v, (set, frozenset)):
        return [prepare_json(x) for x in v]
    if isinstance(v, float):
        return _json_float(float(v))
    if isinstance(v, int):
        return int(v) if abs(v) < 2**63 else _fragment(str(int(v)))
    if isinstance(v, str):
        return str(v)
    return v


def _json_float(v: float) -> Any:
    if v != v or v in (INF, -INF):
        return None
    a = abs(v)
    if v.is_integer():
        if a < 9.2e18:
            return int(v)
        return _fragment(_num_to_str(v))  # JS prints full digits up to 1e21
    if a < 1e-4:
        return _fragment(_num_to_str(v))  # orjson switches to exponent form earlier than JS (1e-7)
    return v


def _fragment(s: str) -> Any:
    import orjson

    return orjson.Fragment(s.encode())


def _copy_until(d: dict, stop: Any) -> dict:
    out = {}
    for k, x in d.items():
        if k == stop:
            break
        out[k] = x
    return out


def js_json_dumps(v: Any) -> bytes:
    """JSON.stringify(v) as bytes (compact)."""
    import orjson

    pv = prepare_json(v)
    try:
        return orjson.dumps(pv, option=orjson.OPT_NON_STR_KEYS)
    except TypeError:
        # an int beyond 64 bits (JS would hold it as a double): print it like JS does
        return orjson.dumps(_big_ints(pv), option=orjson.OPT_NON_STR_KEYS)


def _big_ints(v: Any) -> Any:
    if type(v) is int and not -(2**63) <= v < 2**63:
        return _fragment(_num_to_str(float(v)))
    if isinstance(v, dict):
        return {k: _big_ints(x) for k, x in v.items()}
    if isinstance(v, list):
        return [_big_ints(x) for x in v]
    return v


def prop(obj: Any, key: str) -> Any:
    """`obj.key` / `obj?.key`: UNDEF when the key is absent (or obj is null/undefined) — keeps JSON key omission exact."""
    if obj is None or obj is UNDEF:
        return UNDEF
    return obj.get(key, UNDEF)


def utf16_units(s: str) -> str:
    """the string as JS sees it: astral characters split into surrogate pairs (for regexes without the `u` flag and
    index arithmetic that must match JS: `.` / [^…] match ONE code unit in JS)."""
    if all(ord(c) <= 0xFFFF for c in s):
        return s
    out = []
    for c in s:
        o = ord(c)
        if o > 0xFFFF:
            o -= 0x10000
            out.append(chr(0xD800 + (o >> 10)))
            out.append(chr(0xDC00 + (o & 0x3FF)))
        else:
            out.append(c)
    return ''.join(out)


def _to_int_or_inf(x: Any) -> float | int:
    n = _num(x)
    if n != n:
        return 0
    if n in (INF, -INF):
        return n
    return math.trunc(n)


def js_slice(seq: Any, start: Any = 0, end: Any = UNDEF) -> Any:
    """Array.prototype.slice / String.prototype.slice with JS argument coercion (NaN -> 0, negatives from the end,
    fractions truncated, undefined end = length)."""
    n = len(seq)
    s = _to_int_or_inf(0 if start is UNDEF or start is None else start)
    e = n if end is UNDEF else _to_int_or_inf(end)
    s = max(n + s, 0) if s < 0 else min(s, n)
    e = max(n + e, 0) if e < 0 else min(e, n)
    return seq[int(s) : int(e)] if e > s else seq[0:0]


def js_spread(v: Any) -> dict:
    """the own enumerable properties `{...v}` contributes to an object literal (objects: their entries; arrays and
    strings: index keys; null/undefined/numbers/booleans: nothing)"""
    if isinstance(v, dict):
        return dict(v)
    if isinstance(v, (list, tuple)):
        return {str(i): x for i, x in enumerate(v)}
    if isinstance(v, str):
        return {str(i): c for i, c in enumerate(utf16_units(v))}
    return {}
