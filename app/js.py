def _num(x: Any) -> float | int:
    return x if isinstance(x, (int, float)) and not isinstance(x, bool) else js_number(x)


def is_nan(x: Any) -> bool:
    """Number.isNaN(x) for numbers; for other values use is_nan(js_number(x)) (= global isNaN)."""
    return isinstance(x, float) and x != x


def is_finite(x: Any) -> bool:
    """Number.isFinite: only numbers (not numeric strings)."""
    if isinstance(x, bool) or not isinstance(x, (int, float)):
        return False
    return not (isinstance(x, float) and (x != x or x in (INF, -INF)))


def is_integer(x: Any) -> bool:
    """Number.isInteger."""
    if not is_finite(x):
        return False
    return isinstance(x, int) or float(x).is_integer()


def _intify(x: float) -> int | float:
    """an integral float as int (so it prints like JS); other values unchanged"""
    if isinstance(x, float) and x == x and x not in (INF, -INF) and x.is_integer() and abs(x) < 9007199254740992:
        return int(x)
    return x


def js_round(x: Any) -> int | float:
    """Math.round: half up (towards +∞), exact for every double (Math.round(0.49999999999999994) === 0)."""
    x = _num(x)
    if isinstance(x, int):
        return x
    if x != x or x in (INF, -INF):
        return x
    f = math.floor(x)
    r = f + 1 if x - f >= 0.5 else f
    return int(r) if abs(r) < 9007199254740992 else float(r)


def js_floor(x: Any) -> int | float:
    x = _num(x)
    if isinstance(x, float) and (x != x or x in (INF, -INF)):
        return x
    return math.floor(x)


def js_ceil(x: Any) -> int | float:
    x = _num(x)
    if isinstance(x, float) and (x != x or x in (INF, -INF)):
        return x
    return math.ceil(x)


def js_trunc(x: Any) -> int | float:
    x = _num(x)
    if isinstance(x, float) and (x != x or x in (INF, -INF)):
        return x
    return math.trunc(x)


def to_fixed(x: Any, digits: int = 0) -> str:
    """Number.prototype.toFixed: the EXACT binary value rounded half away from zero (1.005.toFixed(2) === '1.00')."""
    x = _num(x)
    if x != x:
        return 'NaN'
    if x in (INF, -INF):
        return 'Infinity' if x > 0 else '-Infinity'
    if abs(x) >= 1e21:
        return js_str(x)
    neg = x < 0
    with localcontext(Context(prec=500)):
        d = Decimal(abs(x)).quantize(Decimal(1).scaleb(-digits), rounding=ROUND_HALF_UP)
    s = format(d, 'f')
    return ('-' if neg else '') + s


def js_str(x: Any) -> str:
    """String(x) / `${x}` for any value (numbers use the JS shortest round-trip format)."""
    if x is None:
        return 'null'
    if x is UNDEF:
        return 'undefined'
    if x is True:
        return 'true'
    if x is False:
        return 'false'
    if isinstance(x, str):
        return x
    if isinstance(x, int):
        return str(x)
    if isinstance(x, float):
        return _num_to_str(x)
    if isinstance(x, (list, tuple)):
        return ','.join('' if nullish(v) else js_str(v) for v in x)
    if isinstance(x, dict):
        return '[object Object]'
    return str(x)


def _num_to_str(x: float) -> str:
    if x != x:
        return 'NaN'
    if x == INF:
        return 'Infinity'
    if x == -INF:
        return '-Infinity'
    if x == 0:
        return '0'
    if x.is_integer() and abs(x) < 1e21:
        return str(int(x))
    r = repr(x)
    neg = r.startswith('-')
    if neg:
        r = r[1:]
    # digits + exponent from Python's shortest repr (same digits as JS: both shortest round-trip)
    if 'e' in r:
        mant, exp = r.split('e')
        e = int(exp)
    else:
        mant, e = r, 0
    if '.' in mant:
        ip, fp = mant.split('.')
    else:
        ip, fp = mant, ''
    digits = (ip + fp).lstrip('0')
    # n = position of the decimal point relative to the digit string start
    n = len(ip) + e - (len(ip + fp) - len((ip + fp).lstrip('0')))
    digits = digits.rstrip('0') or '0'
    k = len(digits)
    if k <= n <= 21:
        s = digits + '0' * (n - k)
    elif 0 < n <= 21:
        s = digits[:n] + '.' + digits[n:]
    elif -6 < n <= 0:
        s = '0.' + '0' * (-n) + digits
    else:
        ee = n - 1
        s = digits[0] + ('.' + digits[1:] if k > 1 else '') + 'e' + ('+' if ee >= 0 else '-') + str(abs(ee))
    return ('-' if neg else '') + s


_JS_WS = '\u0009\u000a\u000b\u000c\u000d                  　﻿'
_DEC_RE = re.compile(r'^[+-]?(?:Infinity|(?:\d+\.?\d*|\.\d+)(?:[eE][+-]?\d+)?)$', re.ASCII)


def js_trim(s: str) -> str:
    """String.prototype.trim (JS whitespace + line terminators)."""
    return s.strip(_JS_WS)


def js_trim_start(s: str) -> str:
    return s.lstrip(_JS_WS)


def js_trim_end(s: str) -> str:
    return s.rstrip(_JS_WS)


def js_number(v: Any) -> int | float:
    """Number(v). Returns an int when the result is integral (prints like JS), else a float (NaN for junk)."""
    if v is None or v is False:
        return 0
    if v is True:
        return 1
    if v is UNDEF:
        return NAN
    if isinstance(v, int):
        return v
    if isinstance(v, float):
        return v
    if isinstance(v, str):
        s = js_trim(v)
        if s == '':
            return 0
        low = s[:2].lower()
        if low in ('0x', '0o', '0b') and len(s) > 2:
            try:
                return int(s[2:], {'0x': 16, '0o': 8, '0b': 2}[low])
            except ValueError:
                return NAN
        if not _DEC_RE.match(s):
            return NAN
        f = float(s)
        return _intify(f)
    if isinstance(v, (list, tuple)):
        return js_number(js_str(v))
    return NAN


_INT_RE = re.compile(r'^[+-]?[0-9]+', re.ASCII)


def js_parse_int(v: Any, radix: int | None = None) -> int | float:
    """parseInt(v, radix)."""
    s = js_trim_start(js_str(v))
    sign = 1
    if s[:1] in '+-' and s:
        sign = -1 if s[0] == '-' else 1
        s = s[1:]
    r = radix or 10
    if (radix in (None, 0, 16)) and s[:2].lower() == '0x':
        s, r = s[2:], 16
    if r < 2 or r > 36:
        return NAN
    digits = '0123456789abcdefghijklmnopqrstuvwxyz'[:r]
    n = 0
    for i, ch in enumerate(s.lower()):
        if ch not in digits:
            s = s[:i]
            break
    if not s:
        return NAN
    n = int(s, r)
    return sign * n


_FLOAT_RE = re.compile(r'^[+-]?(?:Infinity|(?:\d+\.?\d*|\.\d+)(?:[eE][+-]?\d+)?)', re.ASCII)


def js_parse_float(v: Any) -> int | float:
    """parseFloat(v)."""
    s = js_trim_start(js_str(v))
    m = _FLOAT_RE.match(s)
    if not m:
        # a trailing exponent marker without digits ("1e") is not part of the number
        m2 = re.match(r'^[+-]?(?:\d+\.?\d*|\.\d+)', s, re.ASCII)
        if not m2:
            return NAN
        return _intify(float(m2.group(0)))
    t = m.group(0)
    if t.endswith(('e', 'E', 'e+', 'e-', 'E+', 'E-')):
        t = re.sub(r'[eE][+-]?$', '', t)
    return _intify(float(t.replace('Infinity', 'inf')))


def js_div(a: Any, b: Any) -> int | float:
    """a / b with JS semantics (x/0 = ±Infinity, 0/0 = NaN) — never raises."""
    a, b = _num(a), _num(b)
    if b == 0:
        if a != a or a == 0:
            return NAN
        neg = (a < 0) != (math.copysign(1.0, b) < 0)
        return -INF if neg else INF
    return a / b


def js_mod(a: Any, b: Any) -> int | float:
    """a % b with JS semantics: the sign follows the dividend (-7 % 3 === -1); x % 0 = NaN."""
    a, b = _num(a), _num(b)
    if b == 0 or a != a or b != b or a in (INF, -INF):
        return NAN
    if b in (INF, -INF):
        return a
    r = math.fmod(a, b)
    return int(r) if isinstance(a, int) and isinstance(b, int) else r


def js_max(*xs: Any) -> int | float:
    """Math.max(...xs): -Infinity when empty, NaN when any is NaN. Accepts one iterable or several args."""
    vals = list(xs[0]) if len(xs) == 1 and isinstance(xs[0], (list, tuple, set, frozenset)) else list(xs)
    if not vals:
        return -INF
    out: Any = -INF
    for v in vals:
        v = _num(v)
        if v != v:
            return NAN
        if v > out:
            out = v
    return out


def js_min(*xs: Any) -> int | float:
    """Math.min(...xs): +Infinity when empty, NaN when any is NaN."""
    vals = list(xs[0]) if len(xs) == 1 and isinstance(xs[0], (list, tuple, set, frozenset)) else list(xs)
    if not vals:
        return INF
    out: Any = INF
    for v in vals:
        v = _num(v)
        if v != v:
            return NAN
        if v < out:
            out = v
    return out


def clamp(x: float, lo: float, hi: float) -> float:
    """Math.min(hi, Math.max(lo, x))."""
    return js_min(hi, js_max(lo, x))


