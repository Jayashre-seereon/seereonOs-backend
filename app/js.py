def js_len(s: str) -> int:
    """String length in UTF-16 code units (astral characters count 2, like JS)."""
    n = len(s)
    for ch in s:
        if ord(ch) > 0xFFFF:
            n += 1
    return n


def js_split(s: str, sep: str | re.Pattern[str] | None = None, limit: int | None = None) -> list[str]:
    """String.prototype.split: '' splits into characters; a regex separator; `limit` truncates the result."""
    if sep is None:
        out = [s]
    elif isinstance(sep, re.Pattern):
        out = sep.split(s) if sep.groups == 0 else [x for x in sep.split(s) if x is not None]
        if s == '' and out == ['']:
            out = [] if sep.match('') else ['']
    elif sep == '':
        out = list(s)
    else:
        out = s.split(sep)
    return out if limit is None else out[: max(0, limit)]


def pad_start(s: Any, width: int, fill: str = ' ') -> str:
    s = js_str(s)
    if len(s) >= width or not fill:
        return s
    need = width - len(s)
    return (fill * (need // len(fill) + 1))[:need] + s


def pad_end(s: Any, width: int, fill: str = ' ') -> str:
    s = js_str(s)
    if len(s) >= width or not fill:
        return s
    need = width - len(s)
    return s + (fill * (need // len(fill) + 1))[:need]


def js_template(*parts: Any) -> str:
    """`a${b}c` = js_template('a', b, 'c'): every part through String(x) (null -> 'null', UNDEF -> 'undefined')."""
    return ''.join(js_str(p) for p in parts)


def js_join(items: Iterable[Any], sep: str = ',') -> str:
    """Array.prototype.join: null/undefined items become ''."""
    return sep.join('' if nullish(v) else js_str(v) for v in items)


def js_lower(s: str) -> str:
    return s.lower()


def js_upper(s: str) -> str:
    return s.upper()


_URI_UNRESERVED = frozenset("ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789-_.!~*'()")


def encode_uri_component(s: Any) -> str:
    out = []
    for ch in js_str(s):
        if ch in _URI_UNRESERVED:
            out.append(ch)
        else:
            out.extend('%%%02X' % b for b in ch.encode('utf-8', 'surrogatepass'))
    return ''.join(out)


class URIError(ValueError):
    pass


def decode_uri_component(s: str) -> str:
    """decodeURIComponent; raises URIError on malformed sequences (like JS)."""
    if '%' not in s:
        return s
    out = bytearray()
    i = 0
    n = len(s)
    res: list[str] = []
    while i < n:
        ch = s[i]
        if ch == '%':
            h = s[i + 1 : i + 3]
            if len(h) != 2 or not all(c in '0123456789abcdefABCDEF' for c in h):
                raise URIError('URI malformed')
            out.append(int(h, 16))
            i += 3
            continue
        if out:
            try:
                res.append(out.decode('utf-8'))
            except UnicodeDecodeError as e:
                raise URIError('URI malformed') from e
            out = bytearray()
        res.append(ch)
        i += 1
    if out:
        try:
            res.append(out.decode('utf-8'))
        except UnicodeDecodeError as e:
            raise URIError('URI malformed') from e
    return ''.join(res)


