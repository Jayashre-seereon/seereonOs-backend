-- V005: pending_tokens — short-lived per-user state between two requests that used to live in API process memory
-- (src/mock: 2FA setup secret until /me/2fa/verify, WBS import preview until /projects/:id/wbs/import commit).
-- In memory it broke multi-instance deployments (the second request may land on another instance) and restarts.
-- Same conventions as V002–V004 (hand-written; the generator's model predates this table):
--   kind        'two_factor_setup' (id random, payload {secret}) | 'wbs_import' (id = the preview token,
--               ref_id = project id, payload {rows, signature})
--   expires_at  30 min (2FA) / 15 min (WBS); expired rows are ignored and purged by the next write of that kind.
-- Not exported by the tenant data export (settings.ts EXPORT_SKIP).

CREATE TABLE pending_tokens (
  id text NOT NULL DEFAULT gen_random_uuid()::text,
  tenant_id text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  created_by text,
  "version" integer NOT NULL DEFAULT 1,
  kind text NOT NULL CONSTRAINT pending_tokens_kind_chk CHECK (kind IN ('two_factor_setup', 'wbs_import')),
  user_id text NOT NULL,
  ref_id text,
  payload jsonb,
  expires_at timestamptz NOT NULL,
  _null_override text[],
  _ord bigint GENERATED BY DEFAULT AS IDENTITY
);
COMMENT ON TABLE pending_tokens IS 'Row type PendingToken[] (src/mock/server.ts)';
COMMENT ON COLUMN pending_tokens.kind IS '''two_factor_setup'' | ''wbs_import''';
COMMENT ON COLUMN pending_tokens.payload IS 'unknown';

ALTER TABLE pending_tokens ADD CONSTRAINT pending_tokens_pkey PRIMARY KEY (id);
CREATE INDEX pending_tokens_tenant_ord_ix ON pending_tokens (tenant_id, _ord);
CREATE INDEX pending_tokens_tenant_user_kind_ix ON pending_tokens (tenant_id, user_id, kind);
ALTER TABLE pending_tokens ADD CONSTRAINT pending_tokens_tenant_fk FOREIGN KEY (tenant_id) REFERENCES tenants (id) ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED;
-- user_id: no FK (users are never hard-deleted while a token is pending; matches the mock, which has no check)

ALTER TABLE pending_tokens ENABLE ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON pending_tokens USING (tenant_id = current_setting('app.tenant_id', true)) WITH CHECK (tenant_id = current_setting('app.tenant_id', true));
CREATE POLICY platform_admin ON pending_tokens USING (current_setting('app.platform_admin', true) = 'on') WITH CHECK (current_setting('app.platform_admin', true) = 'on');
CREATE TRIGGER pending_tokens_ver_ins AFTER INSERT ON pending_tokens REFERENCING NEW TABLE AS new_rows FOR EACH STATEMENT EXECUTE FUNCTION app_bump_table_versions('tenant_id');
CREATE TRIGGER pending_tokens_ver_upd AFTER UPDATE ON pending_tokens REFERENCING OLD TABLE AS old_rows NEW TABLE AS new_rows FOR EACH STATEMENT EXECUTE FUNCTION app_bump_table_versions('tenant_id');
CREATE TRIGGER pending_tokens_ver_del AFTER DELETE ON pending_tokens REFERENCING OLD TABLE AS old_rows FOR EACH STATEMENT EXECUTE FUNCTION app_bump_table_versions('tenant_id');
GRANT SELECT, INSERT, UPDATE, DELETE ON pending_tokens TO seereon_app;

